"""Export the manifest's Homebrew and App Store tools as a Brewfile."""

import click

from setmac.registry import Registry


def render_brewfile(registry: Registry) -> str:
    taps: list[str] = []
    lines: list[str] = []
    for tool in registry.tools:
        target = tool.install.target
        method = tool.install.method
        if not target:
            continue
        if method in ("brew_formula", "brew_cask") and target.count("/") == 2:
            tap = target.rsplit("/", 1)[0]
            if tap not in taps:
                taps.append(tap)
        if method == "brew_formula":
            lines.append(f'brew "{target}"')
        elif method == "brew_cask":
            lines.append(f'cask "{target}"')
        elif method == "mas":
            lines.append(f'mas "{tool.name}", id: {target}')
    head = [f'tap "{tap}"' for tap in taps]
    return "\n".join(["# Generated by `setmac brewfile` from tools.json", *head, *lines]) + "\n"


@click.command("brewfile")
@click.option("--output", "-o", type=click.Path(dir_okay=False), help="Write to a file instead of stdout")
def brewfile_cmd(output):
    """Print a Brewfile for `brew bundle`, as a fallback to the app."""
    text = render_brewfile(Registry())
    if output:
        with open(output, "w") as f:
            f.write(text)
    else:
        click.echo(text, nl=False)
